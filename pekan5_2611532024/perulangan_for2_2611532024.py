ulang_2024 = int((input)("Masukkan jumlah perulangan: "))
print("Perulangan ke-0 sampai ke-", ulang_2024-1)
for i in range (ulang_2024):
    print(i, end=" ")
print()
print("Perulangan ke-1 sampai ke-", ulang_2024)
for i in range(1,ulang_2024+1):
    print(i, end=" ")
