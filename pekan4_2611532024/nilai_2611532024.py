nilai_2024 = int(input("Masukkan nilai angka = "))

if nilai_2024 >= 81:
    print("A")
elif nilai_2024 >= 70:
    print("B")
elif nilai_2024 >= 60:
    print("C")
elif nilai_2024 >= 50:
    print("D")
else:
    print("E")